#!/usr/bin/env python3
"""
Organize YOLO dataset: validate image/label pairs and create train/val splits.

Usage:
    python tools/organize_yolo_dataset.py --images datasets/yolo_raw/run1/images \
        --output datasets/yolo_dataset --split 0.8
    python tools/organize_yolo_dataset.py --images datasets/yolo_raw/all \
        --output datasets/yolo_dataset --classes enemy,exit,player,progress_panel,objective_counter

Expects YOLO-format label files (one .txt per image) with lines:
    class_id x_center y_center width height  (normalized 0-1)
"""
from __future__ import annotations

import json
import shutil
import random
from pathlib import Path

import typer

app = typer.Typer(help="Organize collected frames into YOLO train/val dataset.")


@app.command()
def organize(
    images: Path = typer.Option(..., "--images", "-i",
                                help="Directory containing raw images"),
    output: Path = typer.Option(Path("datasets/yolo_dataset"), "--output", "-o",
                               help="Output dataset directory"),
    split: float = typer.Option(0.8, "--split", "-s",
                                help="Train fraction (0.0-1.0)"),
    classes: str = typer.Option("enemy,exit,player,progress_panel,objective_counter",
                                "--classes", "-c",
                                help="Comma-separated class names in order"),
    validate: bool = typer.Option(True, "--validate/--no-validate",
                                 help="Check for missing label files"),
) -> None:
    """Split raw images+labels into train/val and write data.yaml."""
    if not images.exists():
        raise typer.BadParameter(f"Images directory not found: {images}")

    output = Path(output)
    train_images = output / "images" / "train"
    val_images = output / "images" / "val"
    train_labels = output / "labels" / "train"
    val_labels = output / "labels" / "val"

    for d in [train_images, val_images, train_labels, val_labels]:
        d.mkdir(parents=True, exist_ok=True)

    class_names = [c.strip() for c in classes.split(",")]
    if len(class_names) < 2:
        raise typer.BadParameter("At least 2 classes required.")

    # Collect all image files
    image_files = sorted(_find_images(images))
    if not image_files:
        raise typer.BadParameter(f"No image files found in {images}")

    print(f"[INFO] Found {len(image_files)} images in {images}")

    # Validate label pairs
    missing_labels: list[str] = []
    for img_path in image_files:
        label_path = img_path.with_suffix(".txt")
        if not label_path.exists():
            missing_labels.append(str(label_path))

    if missing_labels:
        print(f"[WARN] {len(missing_labels)} images missing label files:")
        for lbl in missing_labels[:5]:
            print(f"  - {lbl}")
        if len(missing_labels) > 5:
            print(f"  ... and {len(missing_labels) - 5} more")

        if validate:
            raise typer.BadParameter(
                f"{len(missing_labels)} images missing label files. "
                "Annotate them first, or use --no-validate to skip."
            )

    # Shuffle and split
    random.seed(42)
    shuffled = image_files.copy()
    random.shuffle(shuffled)
    split_idx = int(len(shuffled) * split)
    train_files = shuffled[:split_idx]
    val_files = shuffled[split_idx:]

    print(f"[INFO] Train: {len(train_files)}, Val: {len(val_files)}")

    for img_path in train_files:
        shutil.copy2(img_path, train_images / img_path.name)
        lbl_path = img_path.with_suffix(".txt")
        if lbl_path.exists():
            shutil.copy2(lbl_path, train_labels / lbl_path.name)

    for img_path in val_files:
        shutil.copy2(img_path, val_images / img_path.name)
        lbl_path = img_path.with_suffix(".txt")
        if lbl_path.exists():
            shutil.copy2(lbl_path, val_labels / lbl_path.name)

    # Write data.yaml
    data_yaml = output / "data.yaml"
    content = f"""# YOLO dataset for Cupid Wave 1
# Auto-generated by organize_yolo_dataset.py

path: {output.absolute()}
train: images/train
val: images/val

nc: {len(class_names)}
names: {json.dumps(class_names)}
"""
    data_yaml.write_text(content, encoding="utf-8")

    print(f"[OK] Dataset written to {output}")
    print(f"     Train: {len(train_files)} images")
    print(f"     Val:   {len(val_files)} images")
    print(f"     data.yaml: {data_yaml}")


def _find_images(root: Path) -> list[Path]:
    """Recursively find image files."""
    suffixes = {".jpg", ".jpeg", ".png", ".bmp"}
    result: list[Path] = []
    for ext in suffixes:
        result.extend(root.rglob(f"*{ext}"))
    return sorted(result)


if __name__ == "__main__":
    app()
